/**
 * 마크다운을 카드 요약용 평문으로(#384). 카드는 설명을 2줄로 잘라 보여주는데, 마크다운 문법(`##`, `**`,
 * `![](...)`)이 그대로 보이면 안 된다. 정확한 파서가 아니라 요약에 필요한 만큼만 걷어낸다.
 */
export function markdownToPlainText(markdown: string): string {
  return (
    markdown
      // 이미지는 통째로, 링크는 글자만 남긴다.
      .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // 줄 앞 블록 표시: 제목·인용·목록·구분선.
      .replace(/^\s{0,3}(#{1,6}|>|[-*+]|\d+[.)])\s+/gm, "")
      .replace(/^\s{0,3}([-*_])(\s*\1){2,}\s*$/gm, "")
      // 강조. 밑줄 하나는 단어 경계에서만 — `snake_case` 같은 이름은 그대로 둔다.
      .replace(/(\*\*|__|~~)(.+?)\1/g, "$2")
      .replace(/(^|[^\w*])\*(\S(?:.*?\S)?)\*(?![\w*])/g, "$1$2")
      .replace(/(^|\W)_(\S(?:.*?\S)?)_(?!\w)/g, "$1$2")
      .replace(/`([^`]*)`/g, "$1")
      .replace(/\s+/g, " ")
      .trim()
  );
}
